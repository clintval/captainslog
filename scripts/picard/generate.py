"""Write Picard's metrics dataclasses from the schema that PicardSchema.java prints."""

import argparse
import functools
import html
import itertools
import json
import keyword
import re
import subprocess
import sys
import textwrap
from collections import Counter
from pathlib import Path
from typing import Any

HEADER = "# Generated by scripts/picard/generate.py from Picard {}. Do not edit."
WIDTH = 100
MULTILEVEL = "picard.metrics.MultilevelMetrics"

TYPES = {
    "boolean": ("bool", "False"),
    "byte": ("int", "0"),
    "char": ("str", '""'),
    "double": ("float", "0.0"),
    "float": ("float", "0.0"),
    "htsjdk.samtools.util.Iso8601Date": ("datetime.datetime | None", "None"),
    "int": ("int", "0"),
    "java.lang.Boolean": ("bool | None", "None"),
    "java.lang.Byte": ("int | None", "None"),
    "java.lang.Double": ("float | None", "None"),
    "java.lang.Float": ("float | None", "None"),
    "java.lang.Integer": ("int | None", "None"),
    "java.lang.Long": ("int | None", "None"),
    "java.lang.Object": ("str | None", "None"),
    "java.lang.Short": ("int | None", "None"),
    "java.lang.String": ("str", '""'),
    "java.util.Date": ("datetime.date | None", "None"),
    "long": ("int", "0"),
    "short": ("int", "0"),
}

RENAMES = {
    "picard.analysis.CollectQualityYieldMetricsSNVQ$QualityYieldMetrics": "QualityYieldMetricsSnvq",
}

ENUM_RENAMES = {
    "htsjdk.variant.variantcontext.VariantContext$Type": "VariantType",
    "picard.analysis.CollectWgsMetricsWithNonZeroCoverage$WgsMetricsWithNonZeroCoverage$Category": (
        "WgsMetricsWithNonZeroCoverageCategory"
    ),
}

# Its fields hold a whole metrics file and a summary bean, so htsjdk cannot write it as columns.
SKIPPED = {"picard.metrics.GcBiasMetrics"}

TOKENS = re.compile(
    r'/\*\*(?P<doc>.*?)\*/|/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|(?P<end>[{};])',
    re.DOTALL,
)
TYPE_DECLARATION = re.compile(r"\b(?:class|enum|interface|record)\s+(\w+)")
FIELD_DECLARATION = re.compile(r"(\w+)\s*(?:=.*)?$", re.DOTALL)


@functools.cache
def javadocs(path: Path) -> dict[str, str]:
    """The Javadocs in a Java file, by type (`Outer$Inner`) and by field (`Outer$Inner.FIELD`)."""
    text = path.read_text()
    docs: dict[str, str] = {}
    scopes: list[str] = []
    head, doc, start = "", "", 0
    for token in TOKENS.finditer(text):
        head, start = head + text[start : token.start()], token.end()
        if token["doc"] is not None:
            doc = token["doc"]
        if token["end"] is None:
            continue
        owner = "$".join(scopes) if "" not in scopes else ""
        if token["end"] == "{":
            declared = TYPE_DECLARATION.search(head)
            scopes.append(declared[1] if declared and (owner or not scopes) else "")
            if doc and scopes[-1]:
                docs["$".join(scopes)] = doc
        elif token["end"] == "}":
            _ = scopes.pop()
        elif doc and owner and (declared := FIELD_DECLARATION.search(head.strip())):
            docs[f"{owner}.{declared[1]}"] = doc
        head, doc = "", ""
    return docs


def paragraphs(doc: str) -> list[str]:
    """The paragraphs of a Javadoc as plain text, without its tags."""
    lines = (re.sub(r"^\s*\*? ?", "", line) for line in doc.rstrip("*\n\t ").splitlines())
    text = "\n".join(itertools.takewhile(lambda line: not line.lstrip().startswith("@"), lines))
    text = re.sub(r"\{@\w+\s+([^}]*)\}", lambda m: m[1].strip().lstrip("#").replace("#", "."), text)
    chunks = re.split(r"\n\s*\n|<p\b[^>]*>|</p>", text, flags=re.IGNORECASE)
    plain = (html.unescape(re.sub(r"</?[a-zA-Z][^>]*>", " ", chunk)) for chunk in chunks)
    return [" ".join(chunk.split()) for chunk in plain if chunk.strip()]


def javadoc(source: Path, java: str, member: str | None = None) -> list[str]:
    """The paragraphs of the Javadoc of a Java type, or of one of its fields."""
    package, _, nested = java.rpartition(".")
    path = source / "src/main/java" / package.replace(".", "/") / f"{nested.split('$')[0]}.java"
    if not path.exists():
        if java.startswith("htsjdk."):
            return []
        raise SystemExit(f"{java} has no source file at {path}!")
    doc = javadocs(path).get(nested if member is None else f"{nested}.{member}")
    return paragraphs(doc) if doc else []


def class_summary(source: Path, java: str) -> str:
    """The first paragraph of a type's Javadoc, ending in a period, or else its Java name."""
    found = javadoc(source, java)
    if not found:
        owner = "htsjdk" if java.startswith("htsjdk.") else "Picard"
        return f"{owner}'s `{java.rpartition('.')[2]}`."
    summary = found[0].rstrip(":;, ")
    return summary if summary.endswith((".", "?", "!")) else f"{summary}."


def docstring(texts: list[str], indent: str) -> list[str]:
    """The source lines of a docstring holding these paragraphs."""
    texts = [text.replace("\\", "\\\\") for text in texts]
    line = f'{indent}"""{texts[0]}"""'
    if len(texts) == 1 and len(line) <= WIDTH and not texts[0].endswith('"'):
        return [line]
    wrap = functools.partial(
        textwrap.wrap, width=WIDTH - len(indent) - 3, break_long_words=False, break_on_hyphens=False
    )
    lines = wrap(texts[0], initial_indent='"""')
    for text in texts[1:]:
        lines += ["", *wrap(text)]
    return [f"{indent}{line}" if line else "" for line in [*lines, '"""']]


def simple_name(java: str) -> str:
    """The name of a Java type without its package and the types it is nested in."""
    return java.rpartition(".")[2].rpartition("$")[2]


def python_type(owner: str, field: dict[str, str], enums: dict[str, str]) -> tuple[str, str]:
    """The annotation and default of a Java field in Python; a required field has no default."""
    kind = field["type"]
    if kind in enums:
        return enums[kind], ""
    if kind == "java.lang.String" and field["declared_by"] == MULTILEVEL:
        return "str | None", "None"
    if kind not in TYPES:
        raise SystemExit(f"{owner}.{field['name']} is a {kind}, which has no Python type!")
    return TYPES[kind]


def field_name(java: str) -> str:
    """The snake_case name of a Java field, with a trailing underscore after a keyword.

    A camelCase name gets an underscore before each capital that follows a lowercase letter or
    a digit; an UPPER_SNAKE name, such as `PCT_10X`, is only lowercased.
    """
    if re.search("[a-z]", java):
        java = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", java)
    name = java.lower()
    return f"{name}_" if keyword.iskeyword(name) else name


def column_labels(java: str, fields: list[dict[str, str]]) -> dict[str, str]:
    """The column label of each field of a Java class, by its Python name."""
    labels = {field_name(field["name"]): field["name"] for field in fields}
    if len(labels) < len(fields):
        raise SystemExit(f"Two fields of {java} have the same Python name!")
    return labels


def metrics_module(
    schema: dict[str, Any], source: Path, classes: dict[str, str], enums: dict[str, str]
) -> str:
    """The source of the module holding every enum and dataclass."""
    fields = {metric["class"]: metric["fields"] for metric in schema["classes"]}
    body: list[str] = []
    for java, name in sorted(enums.items(), key=lambda item: item[1]):
        body += ["", "", f"class {name}(StrEnum):"]
        body += docstring([class_summary(source, java)], "    ")
        body += ["", *(f'    {constant} = "{constant}"' for constant in schema["enums"][java])]
    for java, name in sorted(classes.items(), key=lambda item: item[1]):
        body += ["", "", "@dataclass(frozen=True, kw_only=True)", f"class {name}:"]
        body += docstring([class_summary(source, java)], "    ")
        for attribute, field in zip(column_labels(java, fields[java]), fields[java], strict=True):
            annotation, default = python_type(java, field, enums)
            body += ["", f"    {attribute}: {annotation}" + (default and f" = {default}")]
            if found := javadoc(source, field["declared_by"], field["name"]):
                body += docstring(found, "    ")
    imports = ["import datetime"] if any("datetime." in line for line in body) else []
    imports += ["from dataclasses import dataclass", "from enum import StrEnum"]
    names = json.dumps(sorted([*classes.values(), *enums.values()]))
    header = [HEADER.format(schema["picard"]), *imports, "", f"__all__ = {names}"]
    return "\n".join([*header, *body, ""])


def java_module(schema: dict[str, Any], classes: dict[str, str]) -> str:
    """The source of the module holding each dataclass's Java name and unusual column labels."""
    fields = {metric["class"]: metric["fields"] for metric in schema["classes"]}
    names: list[str] = []
    labels: list[str] = []
    for java, name in sorted(classes.items()):
        names += [f'    _metrics.{name}: "{java}",']
        unusual = {
            attribute: label
            for attribute, label in column_labels(java, fields[java]).items()
            if attribute.removesuffix("_").upper() != label
        }
        if unusual:
            entries = (f'        "{attribute}": "{label}",' for attribute, label in unusual.items())
            labels += [f"    _metrics.{name}: {{", *entries, "    },"]
    return "\n".join([
        HEADER.format(schema["picard"]),
        "from typing import Any",
        "",
        "from shipslog.picard import _metrics",
        "",
        '__all__ = ["COLUMN_LABELS", "JAVA_NAMES"]',
        "",
        "# fmt: off",
        "JAVA_NAMES: dict[type[Any], str] = {",
        *names,
        "}",
        "# fmt: on",
        "",
        "COLUMN_LABELS: dict[type[Any], dict[str, str]] = {",
        *labels,
        "}",
        "",
    ])


def main() -> None:
    """Write `_metrics.py` and `_java.py` into the output directory and format them."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--schema", type=Path, required=True, help="PicardSchema.java's JSON")
    parser.add_argument("--source", type=Path, required=True, help="a checkout of Picard's source")
    parser.add_argument("--output", type=Path, required=True, help="the directory to write into")
    args = parser.parse_args()
    if not (args.source / "src/main/java/picard").is_dir():
        raise SystemExit(f"{args.source} is not a checkout of Picard's source!")

    schema = json.loads(args.schema.read_text())
    kept = [metric for metric in schema["classes"] if metric["class"] not in SKIPPED]
    used = {field["type"] for metric in kept for field in metric["fields"]}
    classes = {
        metric["class"]: RENAMES.get(metric["class"], simple_name(metric["class"]))
        for metric in kept
    }
    enums = {
        java: ENUM_RENAMES.get(java, simple_name(java)) for java in used & set(schema["enums"])
    }
    counts = Counter([*classes.values(), *enums.values()])
    if clashes := sorted(java for java, name in {**classes, **enums}.items() if counts[name] > 1):
        raise SystemExit(f"Rename these Java types, whose Python names clash: {', '.join(clashes)}")

    paths = [args.output / "_metrics.py", args.output / "_java.py"]
    _ = paths[0].write_text(metrics_module(schema, args.source, classes, enums))
    _ = paths[1].write_text(java_module(schema, classes))
    _ = subprocess.run([sys.executable, "-m", "ruff", "format", *map(str, paths)], check=True)


if __name__ == "__main__":
    main()
