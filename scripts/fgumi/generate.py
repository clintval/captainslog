"""Write fgumi's metrics dataclasses from its metric column contract and the structs behind it."""

import argparse
import functools
import json
import keyword
import re
import subprocess
import sys
import textwrap
import tomllib
from collections import Counter
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path

from captainslog._fulcrum import ReadType

HEADER = "# Generated by scripts/fgumi/generate.py from fgumi {}. Do not edit."

WIDTH = 100

MANIFEST = "crates/fgumi-metrics/metric_columns.json"
CONTRACT = "tests/integration/test_metric_contract.rs"

TYPES = {
    "String": ("str", '""'),
    "bool": ("bool", "False"),
    "char": ("str", '""'),
    "f32": ("float", "0.0"),
    "f64": ("float", "0.0"),
    "i32": ("int", "0"),
    "i64": ("int", "0"),
    "u8": ("int", "0"),
    "u16": ("int", "0"),
    "u32": ("int", "0"),
    "u64": ("int", "0"),
    "usize": ("int", "0"),
}

# The base of each coordinate field whose doc comment does not say it, as the source that sets it shows.
COORDINATE_BASES: dict[str, str] = {}

# Enumerations that other tools write too, which the module imports rather than declares.
SHARED_ENUMS: dict[str, type[StrEnum]] = {
    "ReadType": ReadType,
}

ITEM = re.compile(r"^[ \t]*pub (?P<kind>struct|enum) (?P<name>\w+)\b[^{;\n]*\{", re.MULTILINE)
FIELD = re.compile(r"^pub (?P<name>\w+): (?P<type>.+?),?$")
VARIANT = re.compile(r"^(\w+),?$")
EMPHASIS = re.compile(r"(\*\*|__)(?=\S)(.+?)(?<=\S)\1")
OPTION = re.compile(r"^Option<(.+)>$")


@dataclass(frozen=True)
class Field:
    """A serialized field of a Rust struct: its column, its Rust type, and its doc comment."""

    column: str
    rust: str
    doc: list[str]


@dataclass(frozen=True)
class Struct:
    """A Rust struct that fgumi serializes as a metrics file."""

    name: str
    path: str
    doc: list[str]
    fields: list[Field]


def paragraphs(lead: list[str]) -> list[str]:
    """The paragraphs of the `///` doc comment among the lines before an item, as plain text."""
    lines = [line[3:].removeprefix(" ") for line in lead if line.startswith("///")]
    chunks = re.split(r"\n\s*\n", "\n".join(lines))
    return [" ".join(EMPHASIS.sub(r"\2", chunk).split()) for chunk in chunks if chunk.strip()]


def serde(lead: list[str]) -> str:
    """The text inside every `#[serde(...)]` attribute among the lines before an item."""
    return " ".join(found for line in lead for found in re.findall(r"#\[serde\((.*?)\)\]", line))


def is_lead(line: str) -> bool:
    """Whether a stripped line is a comment or an attribute, which may come before an item."""
    return line.startswith(("//", "#["))


@functools.cache
def items(source: Path) -> dict[tuple[str, str], tuple[str, list[str], list[str]]]:
    """Each public struct and enum of fgumi's library and crates, by kind and name.

    Each comes with its path, the comment and attribute lines before it, and the stripped lines of
    its body. The first item of a name wins, and test directories are left out.
    """
    found: dict[tuple[str, str], tuple[str, list[str], list[str]]] = {}
    roots = [source / "src", source / "crates"]
    for path in sorted(
        path for root in roots for path in root.rglob("*.rs") if "tests" not in path.parts
    ):
        text = path.read_text()
        lines = text.splitlines()
        for match in ITEM.finditer(text):
            number = text.count("\n", 0, match.start())
            lead: list[str] = []
            while number - len(lead) > 0 and is_lead(lines[number - len(lead) - 1].strip()):
                lead.insert(0, lines[number - len(lead) - 1].strip())
            depth, end = 1, match.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(text[end], 0)
                end += 1
            body = [
                line.strip() for line in text[match.end() : end - 1].splitlines() if line.strip()
            ]
            key = (match["kind"], match["name"])
            if key not in found:
                found[key] = (str(path.relative_to(source)), lead, body)
    return found


def find_struct(source: Path, name: str) -> Struct:
    """The serialized fields of a struct, in order, with `skip`ped fields left out."""
    if ("struct", name) not in items(source):
        raise SystemExit(f"fgumi has no struct named {name}!")
    path, lead, body = items(source)[("struct", name)]
    fields: list[Field] = []
    before: list[str] = []
    for line in body:
        if is_lead(line):
            before.append(line)
            continue
        if found := FIELD.match(line):
            attributes = serde(before)
            if "flatten" in attributes:
                raise SystemExit(
                    f"{name}.{found['name']} is flattened, which the generator cannot follow!"
                )
            if not re.search(r"\bskip\b", attributes):
                renamed = re.search(r'rename = "(\w+)"', attributes)
                column = renamed[1] if renamed else found["name"]
                fields.append(Field(column, found["type"].strip(), paragraphs(before)))
        before = []
    return Struct(name, path, paragraphs(lead), fields)


def find_enum(source: Path, name: str) -> tuple[list[str], list[str]]:
    """The doc comment and the serialized names of the unit variants of an enumeration."""
    if ("enum", name) not in items(source):
        raise SystemExit(f"fgumi has no enumeration named {name}!")
    _, lead, body = items(source)[("enum", name)]
    if serde(lead) or any(line.startswith("#[serde") for line in body):
        raise SystemExit(f"{name} renames its variants, which the generator does not follow!")
    variants = [found[1] for line in body if not is_lead(line) and (found := VARIANT.match(line))]
    return paragraphs(lead), variants


LOWER_NAMES = ("fgbio", "fgumi", "htsjdk")


def sentence(text: str) -> str:
    """A paragraph as a sentence: capitalized, unless it starts with a tool's name, and ended.

    An em dash, which this project's prose does not use, becomes the colon it stands for.
    """
    text = text.replace(" \u2014 ", ": ").replace("\u2014", ": ")
    if not text.startswith(LOWER_NAMES):
        text = text[:1].upper() + text[1:]
    return text if text.endswith((".", "?", "!")) else f"{text}."


def docstring(texts: list[str], indent: str) -> list[str]:
    """The source lines of a docstring holding these paragraphs, each ending a sentence."""
    texts = [sentence(text).replace("\\", "\\\\") for text in texts]
    line = f'{indent}"""{texts[0]}"""'
    if len(texts) == 1 and len(line) <= WIDTH and not texts[0].endswith('"'):
        return [line]
    wrap = functools.partial(
        textwrap.wrap, width=WIDTH - len(indent) - 3, break_long_words=False, break_on_hyphens=False
    )
    lines = wrap(texts[0], initial_indent='"""')
    for text in texts[1:]:
        lines += ["", *wrap(text)]
    return [f"{indent}{line}" if line else "" for line in [*lines, '"""']]


def summary(found: list[str], name: str) -> str:
    """The first paragraph of a doc comment, ending in a period, or else the item's Rust name."""
    if not found:
        return f"fgumi's `{name}`."
    text = found[0].rstrip(":;, ")
    return text if text.endswith((".", "?", "!")) else f"{text}."


def member_name(variant: str) -> str:
    """The UPPER_SNAKE name of an enumeration member, from its Rust variant."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", variant).upper()


def python_type(owner: str, field: Field, enums: dict[str, list[str]]) -> tuple[str, str]:
    """The annotation and default of a field in Python; a required field has no default."""
    rust, optional = field.rust, False
    if found := OPTION.match(rust):
        rust, optional = found[1], True
    if rust in enums:
        return (f"{rust} | None", "None") if optional else (rust, "")
    if rust not in TYPES:
        raise SystemExit(f"{owner}.{field.column} is a {field.rust}, which has no Python type!")
    annotation, default = TYPES[rust]
    return (f"{annotation} | None", "None") if optional else (annotation, default)


def shared_import(kind: type[StrEnum], variants: list[str]) -> str:
    """The import of an enumeration that other tools write too, which must hold fgumi's variants."""
    if (found := [member.value for member in kind]) != variants:
        raise SystemExit(
            f"{kind.__name__} holds {found}, not the variants fgumi writes: {variants}"
        )
    return f"from {kind.__module__} import {kind.__name__}"


def metrics_module(
    version: str, structs: dict[str, Struct], enums: dict[str, tuple[list[str], list[str]]]
) -> str:
    """The source of the module holding every dataclass, and the enumerations no other tool shares."""
    variants = {name: found for name, (_, found) in enums.items()}
    body: list[str] = []
    shared: list[str] = []
    for name, (doc, found) in sorted(enums.items()):
        if name in SHARED_ENUMS:
            shared += [shared_import(SHARED_ENUMS[name], found)]
            continue
        body += ["", "", f"class {name}(StrEnum):", *docstring([summary(doc, name)], "    "), ""]
        body += [f'    {member_name(variant)} = "{variant}"' for variant in found]
    for name, struct in sorted(structs.items()):
        body += ["", "", "@dataclass(frozen=True, kw_only=True)", f"class {name}:"]
        body += docstring([summary(struct.doc, name)], "    ")
        for field in struct.fields:
            if keyword.iskeyword(field.column):
                raise SystemExit(f"{name}.{field.column} is a Python keyword!")
            annotation, default = python_type(name, field, variants)
            body += ["", f"    {field.column}: {annotation}" + (default and f" = {default}")]
            found = field.doc
            if base := COORDINATE_BASES.get(f"{name}.{field.column}"):
                found = [*found, base]
            if found:
                body += docstring(found, "    ")
    names = json.dumps(sorted([*structs, *enums]))
    header = [HEADER.format(version), "from dataclasses import dataclass"]
    header += ["from enum import StrEnum"] if set(enums) - set(SHARED_ENUMS) else []
    header += ["", *sorted(shared)] if shared else []
    return "\n".join([*header, "", f"__all__ = {names}", *body, ""])


def python_tuple(texts: list[str]) -> str:
    """The source of a tuple of strings."""
    quoted = [json.dumps(text) for text in texts]
    return f"({quoted[0]},)" if len(quoted) == 1 else f"({', '.join(quoted)})"


def rust_module(version: str, structs: dict[str, Struct], keys: dict[str, list[str]]) -> str:
    """The source of the module holding the Rust source and metrics files of each dataclass."""
    paths = [f'    _metrics.{name}: "{struct.path}",' for name, struct in sorted(structs.items())]
    files = [
        f"    _metrics.{name}: {python_tuple(sorted(keys[name]))}," for name in sorted(structs)
    ]
    return "\n".join([
        HEADER.format(version),
        "from typing import Any",
        "",
        "from captainslog.fgumi import _metrics",
        "",
        '__all__ = ["MANIFEST_KEYS", "RUST_SOURCES"]',
        "",
        "# fmt: off",
        "RUST_SOURCES: dict[type[Any], str] = {",
        *paths,
        "}",
        "",
        "MANIFEST_KEYS: dict[type[Any], tuple[str, ...]] = {",
        *files,
        "}",
        "# fmt: on",
        "",
    ])


def main() -> None:
    """Write `_metrics.py` and `_rust.py` into the output directory and format them."""
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--source", type=Path, required=True, help="a checkout of fgumi")
    _ = parser.add_argument("--output", type=Path, required=True, help="the directory to write to")
    _ = parser.add_argument("--manifest", type=Path, help="where to copy fgumi's column contract")
    args = parser.parse_args()
    if not (args.source / MANIFEST).is_file():
        raise SystemExit(f"{args.source} is not a checkout of fgumi's source!")

    version = tomllib.loads((args.source / "Cargo.toml").read_text())["workspace"]["package"][
        "version"
    ]
    manifest: dict[str, list[str]] = json.loads((args.source / MANIFEST).read_text())
    # The contract test pairs each key of the manifest with the struct that writes it.
    pairs = re.findall(r'\(\s*"([\w.]+)",\s*"(\w+)",', (args.source / CONTRACT).read_text())
    if sorted(key for key, _ in pairs) != sorted(manifest):
        raise SystemExit(f"{CONTRACT} does not pair every key of {MANIFEST} with a struct!")

    structs: dict[str, Struct] = {}
    keys: dict[str, list[str]] = {}
    for key, name in pairs:
        struct = structs.setdefault(name, find_struct(args.source, name))
        keys.setdefault(name, []).append(key)
        if (columns := [field.column for field in struct.fields]) != manifest[key]:
            raise SystemExit(
                f"{name} serializes {columns}, not the columns of {key}: {manifest[key]}"
            )
    used = {OPTION.sub(r"\1", field.rust) for struct in structs.values() for field in struct.fields}
    enums = {name: find_enum(args.source, name) for name in sorted(used - set(TYPES))}
    counts = Counter([*structs, *enums])
    if clashes := sorted(name for name, count in counts.items() if count > 1):
        raise SystemExit(f"These Rust types share a name: {', '.join(clashes)}")

    paths = [args.output / "_metrics.py", args.output / "_rust.py"]
    _ = paths[0].write_text(metrics_module(version, structs, enums))
    _ = paths[1].write_text(rust_module(version, structs, keys))
    _ = subprocess.run([sys.executable, "-m", "ruff", "format", *map(str, paths)], check=True)
    if args.manifest:
        _ = args.manifest.write_text(
            json.dumps({"fgumi": version, "files": manifest}, indent=2) + "\n"
        )


if __name__ == "__main__":
    main()
