"""Write fgbio's metrics dataclasses from the schema that FgbioSchema.java prints."""

import argparse
import functools
import json
import keyword
import re
import subprocess
import sys
import textwrap
from collections import Counter
from pathlib import Path
from typing import Any

HEADER = "# Generated by scripts/fgbio/generate.py from fgbio {}. Do not edit."

WIDTH = 100

TYPES = {
    "Any": ("str", '""'),
    "Boolean": ("bool", "False"),
    "Char": ("str", '""'),
    "Double": ("float", "0.0"),
    "Int": ("int", "0"),
    "Long": ("int", "0"),
    "Option[Double]": ("float | None", "None"),
    "Option[String]": ("str | None", "None"),
    "String": ("str", '""'),
}

# Classes that extend Metric to be read or written as tables, but that no fgbio tool writes as metrics.
# fmt: off
SKIPPED = {
    "com.fulcrumgenomics.cmdline.FgBioToolInfo": "a tool's name and arguments, for fgbio's documentation",
    "com.fulcrumgenomics.illumina.RunInfo": "a run read from Illumina's RunInfo.xml",
    "com.fulcrumgenomics.util.Amplicon": "the primer pairs that AssignPrimers and TrimPrimers read",
    "com.fulcrumgenomics.vcf.Sample": "a row of the sequence index that MakeMixtureVcf reads",
}
# fmt: on

ENUM_RENAMES = {
    "htsjdk.samtools.SamPairUtil$PairOrientation": "PairOrientation",
}

ENUM_SUMMARIES = {
    "com.fulcrumgenomics.bam.ReadType": "The reads that a row of `ClipBam`'s metrics counts.",
    "htsjdk.samtools.SamPairUtil$PairOrientation": "htsjdk's `SamPairUtil$PairOrientation`.",
}

# The doc of each field that fgbio's Scaladoc leaves out, as the source that sets it shows.
# fmt: off
FALLBACK_DOCS = {
    "ConsensusKvMetric.description": "What the statistic counts.",
    "ConsensusKvMetric.key": "The name of the statistic, such as `raw_reads_considered`.",
    "ConsensusKvMetric.value": "The statistic, a count or a fraction, kept as the text fgbio writes.",
    "ErrorRateByReadPositionMetric.collapsed": "Whether each complementary substitution is counted with the first six, such as `T>G` with `A>C`, which leaves the `g_to_*` and `t_to_*` rates empty.",
}
# fmt: on

# The base of each coordinate field whose Scaladoc does not say it, as the source that sets it shows.
# fmt: off
COORDINATE_BASES = {
    "ConsensusVariantReviewInfo.pos": "A 1-based position, as htsjdk gives the start of a variant.",
}
# fmt: on

DOC = re.compile(r"/\*\*(?P<doc>.*?)\*/(?P<gap>(?:\s|@\w+(?:\([^)]*\))?)*)", re.DOTALL)
TAG = re.compile(r"^@(\w+)\s*(.*)$", re.DOTALL)
LINK = re.compile(r"\[\[([^\]\s]+)(?:\s+([^\]]+))?\]\]")
EMPHASIS = re.compile(r"(?<![\w`])(\*\*|_)(?=\S)(.+?)(?<=\S)\1(?![\w`])")


def link_text(match: re.Match[str]) -> str:
    """The text of a Scaladoc link: its label, or else the last part of its target."""
    return match[2] if match[2] else f"`{match[1].rpartition('.')[2]}`"


def plain(text: str) -> str:
    """Scaladoc markup as plain text, with links and emphasis taken out."""
    text = LINK.sub(link_text, text)
    return " ".join(EMPHASIS.sub(lambda match: match[2], text).split())


@functools.cache
def scaladocs(source: Path, package: str) -> dict[str, str]:
    """The Scaladoc of each class and trait declared in a package, by simple name."""
    docs: dict[str, str] = {}
    # fgbio keeps a few Scala files under src/main/java.
    roots = [
        source / "src/main" / language / package.replace(".", "/") for language in ("scala", "java")
    ]
    for path in sorted(path for root in roots for path in root.glob("*.scala")):
        text = path.read_text()
        for match in DOC.finditer(text):
            declared = re.match(r"(?:\w+\s+)*(?:class|trait|object)\s+(\w+)", text[match.end() :])
            if declared and declared[1] not in docs:
                docs[declared[1]] = match["doc"]
    return docs


def parse(doc: str) -> tuple[list[str], dict[str, str]]:
    """The paragraphs of a Scaladoc's description, and the text of each of its `@param` tags."""
    lines = [re.sub(r"^\s*\*? ?", "", line) for line in doc.strip("*\n\t ").splitlines()]
    body: list[str] = []
    params: dict[str, list[str]] = {}
    target: list[str] | None = body
    for line in lines:
        if found := TAG.match(line.strip()):
            target = None
            if found[1] == "param":
                name, _, rest = found[2].partition(" ")
                target = params.setdefault(name, [rest])
            continue
        if target is not None:
            target.append(line)
    paragraphs = [plain(chunk) for chunk in re.split(r"\n\s*\n", "\n".join(body)) if chunk.strip()]
    return paragraphs, {name: plain(" ".join(text)) for name, text in params.items()}


def scaladoc(source: Path, scala: str) -> tuple[list[str], dict[str, str]]:
    """The description and `@param` tags of a fgbio class's Scaladoc."""
    package, _, nested = scala.rpartition(".")
    doc = scaladocs(source, package).get(nested.rpartition("$")[2])
    return parse(doc) if doc else ([], {})


def summary(found: list[str], scala: str) -> str:
    """The first paragraph of a description, ending in a period, or else the class's Scala name."""
    if not found:
        return f"fgbio's `{simple_name(scala)}`."
    text = found[0].rstrip(":;, ")
    return text if text.endswith((".", "?", "!")) else f"{text}."


LOWER_NAMES = ("fgbio", "fgumi", "htsjdk")


def sentence(text: str) -> str:
    """A paragraph as a sentence: capitalized, unless it starts with a tool's name, and ended.

    An em dash, which this project's prose does not use, becomes the colon it stands for.
    """
    text = text.replace(" \u2014 ", ": ").replace("\u2014", ": ")
    if not text.startswith(LOWER_NAMES):
        text = text[:1].upper() + text[1:]
    return text if text.endswith((".", "?", "!")) else f"{text}."


def docstring(texts: list[str], indent: str) -> list[str]:
    """The source lines of a docstring holding these paragraphs, each ending a sentence."""
    texts = [sentence(text).replace("\\", "\\\\") for text in texts]
    line = f'{indent}"""{texts[0]}"""'
    if len(texts) == 1 and len(line) <= WIDTH and not texts[0].endswith('"'):
        return [line]
    wrap = functools.partial(
        textwrap.wrap, width=WIDTH - len(indent) - 3, break_long_words=False, break_on_hyphens=False
    )
    lines = wrap(texts[0], initial_indent='"""')
    for text in texts[1:]:
        lines += ["", *wrap(text)]
    return [f"{indent}{line}" if line else "" for line in [*lines, '"""']]


def simple_name(scala: str) -> str:
    """The name of a class without its package and the objects it is nested in."""
    return scala.rpartition(".")[2].rpartition("$")[2]


def member_name(entry: str) -> str:
    """The UPPER_SNAKE name of an enumeration member, from the text fgbio writes for it."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", entry).upper()


def python_type(owner: str, field: dict[str, str], enums: dict[str, str]) -> tuple[str, str]:
    """The annotation and default of a field in Python; a required field has no default."""
    if field["class"] in enums:
        return enums[field["class"]], ""
    if field["type"] not in TYPES:
        raise SystemExit(f"{owner}.{field['name']} is a {field['type']}, which has no Python type!")
    return TYPES[field["type"]]


def metrics_module(
    schema: dict[str, Any], source: Path, classes: dict[str, str], enums: dict[str, str]
) -> str:
    """The source of the module holding every enumeration and dataclass."""
    fields = {metric["class"]: metric["fields"] for metric in schema["classes"]}
    body: list[str] = []
    for scala, name in sorted(enums.items(), key=lambda item: item[1]):
        text = ENUM_SUMMARIES.get(scala) or summary(scaladoc(source, scala)[0], scala)
        body += ["", "", f"class {name}(StrEnum):", *docstring([text], "    "), ""]
        body += [f'    {member_name(entry)} = "{entry}"' for entry in schema["enums"][scala]]
    for scala, name in sorted(classes.items(), key=lambda item: item[1]):
        description, params = scaladoc(source, scala)
        body += ["", "", "@dataclass(frozen=True, kw_only=True)", f"class {name}:"]
        body += docstring([summary(description, scala)], "    ")
        for field in fields[scala]:
            if keyword.iskeyword(field["name"]):
                raise SystemExit(f"{scala}.{field['name']} is a Python keyword!")
            annotation, default = python_type(scala, field, enums)
            body += ["", f"    {field['name']}: {annotation}" + (default and f" = {default}")]
            found = [params[field["name"]]] if params.get(field["name"]) else []
            if not found and (fallback := FALLBACK_DOCS.get(f"{name}.{field['name']}")):
                found = [fallback]
            if base := COORDINATE_BASES.get(f"{name}.{field['name']}"):
                found = [*found, base]
            if found:
                body += docstring(found, "    ")
    names = json.dumps(sorted([*classes.values(), *enums.values()]))
    header = [
        HEADER.format(schema["fgbio"]),
        "from dataclasses import dataclass",
        "from enum import StrEnum",
    ]
    return "\n".join([*header, "", f"__all__ = {names}", *body, ""])


def scala_module(schema: dict[str, Any], classes: dict[str, str]) -> str:
    """The source of the module holding the Scala name of each dataclass."""
    names = [f'    _metrics.{name}: "{scala}",' for scala, name in sorted(classes.items())]
    return "\n".join([
        HEADER.format(schema["fgbio"]),
        "from typing import Any",
        "",
        "from captainslog.fgbio import _metrics",
        "",
        '__all__ = ["SCALA_NAMES"]',
        "",
        "# fmt: off",
        "SCALA_NAMES: dict[type[Any], str] = {",
        *names,
        "}",
        "# fmt: on",
        "",
    ])


def main() -> None:
    """Write `_metrics.py` and `_scala.py` into the output directory and format them."""
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--schema", type=Path, required=True, help="FgbioSchema.java's JSON")
    _ = parser.add_argument("--source", type=Path, required=True, help="a checkout of fgbio")
    _ = parser.add_argument("--output", type=Path, required=True, help="the directory to write to")
    args = parser.parse_args()
    if not (args.source / "src/main/scala/com/fulcrumgenomics").is_dir():
        raise SystemExit(f"{args.source} is not a checkout of fgbio's source!")

    schema = json.loads(args.schema.read_text())
    if missing := sorted(set(SKIPPED) - {metric["class"] for metric in schema["classes"]}):
        raise SystemExit(
            f"Remove these classes, which fgbio no longer has, from SKIPPED: {missing}"
        )
    kept = [metric for metric in schema["classes"] if metric["class"] not in SKIPPED]
    classes = {metric["class"]: simple_name(metric["class"]) for metric in kept}
    used = {field["class"] for metric in kept for field in metric["fields"]}
    enums = {
        scala: ENUM_RENAMES.get(scala, simple_name(scala)) for scala in used & set(schema["enums"])
    }
    counts = Counter([*classes.values(), *enums.values()])
    if clashes := sorted(scala for scala, name in {**classes, **enums}.items() if counts[name] > 1):
        raise SystemExit(
            f"Rename these Scala types, whose Python names clash: {', '.join(clashes)}"
        )

    paths = [args.output / "_metrics.py", args.output / "_scala.py"]
    _ = paths[0].write_text(metrics_module(schema, args.source, classes, enums))
    _ = paths[1].write_text(scala_module(schema, classes))
    _ = subprocess.run([sys.executable, "-m", "ruff", "format", *map(str, paths)], check=True)


if __name__ == "__main__":
    main()
